"""Generate LiteLLM config.yaml from NiyanConfig."""

from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, List

import yaml

from niyan.config import ModelProvider, NiyanConfig


def litellm_model_entry(model_id: str, provider: ModelProvider, api_key: str = "") -> Dict[str, Any]:
    if provider == ModelProvider.ollama:
        return {
            "model_name": model_id,
            "litellm_params": {
                "model": f"ollama/{model_id}",
                "api_base": "os.environ/OLLAMA_API_BASE",
            },
        }
    if provider == ModelProvider.openai:
        params: Dict[str, Any] = {"model": f"openai/{model_id}"}
        if api_key:
            params["api_key"] = api_key
        else:
            params["api_key"] = "os.environ/OPENAI_API_KEY"
        return {"model_name": model_id, "litellm_params": params}
    if provider == ModelProvider.gemini:
        # LiteLLM uses gemini/ prefix for Google AI Studio
        params = {"model": f"gemini/{model_id}"}
        if api_key:
            params["api_key"] = api_key
        else:
            params["api_key"] = "os.environ/GEMINI_API_KEY"
        return {"model_name": model_id, "litellm_params": params}
    if provider == ModelProvider.anthropic:
        params = {"model": f"anthropic/{model_id}"}
        if api_key:
            params["api_key"] = api_key
        else:
            params["api_key"] = "os.environ/ANTHROPIC_API_KEY"
        return {"model_name": model_id, "litellm_params": params}
    raise ValueError(f"unsupported provider: {provider}")


def build_litellm_config(config: NiyanConfig) -> Dict[str, Any]:
    model_list: List[Dict[str, Any]] = []
    for m in config.routable_models():
        key = ""
        if m.provider == ModelProvider.openai:
            key = config.providers.openai.api_key.strip()
        elif m.provider == ModelProvider.gemini:
            key = config.providers.gemini.api_key.strip()
        elif m.provider == ModelProvider.anthropic:
            key = config.providers.anthropic.api_key.strip()
        model_list.append(litellm_model_entry(m.id, m.provider, key))

    # Always expose embedding model via Ollama when embeddings enabled
    if config.embeddings.enabled and config.embeddings.model:
        emb = config.embeddings.model
        if not any(e.get("model_name") == emb for e in model_list):
            model_list.append(litellm_model_entry(emb, ModelProvider.ollama))

    if not model_list:
        # Keep LiteLLM startable with at least one local placeholder
        model_list.append(litellm_model_entry("llama3.2:3b", ModelProvider.ollama))

    return {
        "model_list": model_list,
        "litellm_settings": {
            "drop_params": True,
            "set_verbose": False,
            "success_callback": ["langfuse"],
            "failure_callback": ["langfuse"],
        },
        "general_settings": {
            "master_key": "os.environ/LITELLM_MASTER_KEY",
        },
    }


def generate_litellm_config(config: NiyanConfig, repo_root: Path) -> Path:
    """Write services/litellm/config.generated.yaml and return its path."""
    out = repo_root / "services" / "litellm" / "config.generated.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    payload = build_litellm_config(config)
    header = (
        "# AUTO-GENERATED by Niyan from niyan.yaml — do not edit by hand.\n"
        "# Regenerate: niyan up  |  portal Providers/Models save\n"
    )
    out.write_text(header + yaml.safe_dump(payload, sort_keys=False))
    return out
